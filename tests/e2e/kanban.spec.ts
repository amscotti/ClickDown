import { expect, test } from '@playwright/test';
import { htmxTriggerChange } from './helpers';

test.describe('ClickDown E2E Kanban Workflow', () => {
  const testEmail = `e2e-user-${Date.now()}@example.com`;
  const testPassword = 'Password123!';
  const teamName = `E2E Team ${Date.now()}`;
  const boardName = `E2E Sprint Board ${Date.now()}`;
  const taskTitle = `E2E Test Task ${Date.now()}`;
  const updatedTaskTitle = `Updated E2E Task Title ${Date.now()}`;

  test('should go through the full user registration, team/board creation, task management, and cleanup flow', async ({
    page,
  }) => {
    // Enable browser log mirroring
    page.on('pageerror', (err) => {
      console.error('BROWSER ERROR:', err);
    });
    page.on('console', (msg) => {
      console.log('BROWSER LOG:', msg.text());
    });

    // 1. Visit landing page
    await page.goto('/');
    await expect(page.locator('header nav strong a')).toContainText('ClickDown');
    await expect(page.locator('main h1')).toContainText('ClickDown');
    await expect(page.locator('main h2')).toContainText('Lightweight Kanban Task Management');

    // 2. Go to Register page
    await page.click('text=Register');
    await expect(page).toHaveURL('/register');

    // Fill registration form
    await page.fill('#displayName', 'Alex Playwright');
    await page.fill('#email', testEmail);
    await page.fill('#password', testPassword);
    await page.fill('#confirmPassword', testPassword);
    await page.click('button[type="submit"]');

    // Should redirect to dashboard
    await expect(page).toHaveURL('/dashboard');
    await expect(page.locator('.sidebar strong')).toContainText('Alex Playwright');
    await expect(page.locator('main h2')).toContainText('Welcome to ClickDown!');

    // 3. Create a Team
    await page.click('text=Create Your First Team');
    await expect(page.locator('dialog h3')).toContainText('Create New Team');
    await page.fill('#teamName', teamName);
    await page.fill('#teamDescription', 'An automated E2E testing team');
    await page.click('button[type="submit"]:has-text("Create Team")');

    // Should redirect to the Team page
    await expect(page).toHaveURL(/\/teams\/e2e-team-/);
    await expect(page.locator('.team-header h1')).toContainText(teamName);
    await expect(page.locator('.team-meta')).toContainText('1 member');
    await expect(page.locator('.team-meta')).toContainText('0 boards');

    // 4. Create a Board
    await page.click('text=Create Board');
    await expect(page.locator('dialog h3')).toContainText('Create New Board');
    await page.fill('#boardName', boardName);
    await page.fill('#boardDescription', 'Sprint tasks generated by E2E tests');
    await page.click('button[type="submit"]:has-text("Create Board")');

    // Should redirect to the Board page
    await expect(page).toHaveURL(/\/boards\/e2e-sprint-board-/);
    await expect(page.locator('.board-header h1')).toContainText(boardName);

    // Verify default columns exist
    const columns = page.locator('.kanban-column');
    await expect(columns).toHaveCount(4);
    await expect(columns.nth(0).locator('h3')).toContainText('Backlog');
    await expect(columns.nth(1).locator('h3')).toContainText('To Do');
    await expect(columns.nth(2).locator('h3')).toContainText('In Progress');
    await expect(columns.nth(3).locator('h3')).toContainText('Done');

    // 5. Add a Task to To Do column (index 1)
    const toDoColumn = columns.nth(1);
    await toDoColumn.locator('footer button').click();
    await expect(page.locator('dialog h3')).toContainText('Add New Task');
    await page.fill('#taskTitle', taskTitle);
    await page.fill('#taskDescription', 'This is a task description created by Playwright');
    await page.selectOption('#taskPriority', 'high');
    await page.click('button[type="submit"]:has-text("Create Task")');

    // Verify task is visible in the column
    const taskCard = toDoColumn.locator('.task-card');
    await expect(taskCard).toBeVisible();
    await expect(taskCard.locator('h4')).toContainText(taskTitle);
    await expect(taskCard.locator('.priority-badge')).toContainText('high');

    // 6. Click the Task Card to Open the Detail Modal
    await taskCard.click();
    const detailDialog = page.locator('dialog[open]');
    await expect(detailDialog).toBeVisible();
    await expect(detailDialog.locator('h3')).toContainText('Task Details');

    // 7. Inline Edit Task Details
    // Edit Title
    const titleInput = detailDialog.locator('#taskTitleInput');
    const updateTitlePromise = page.waitForResponse(
      (response) => response.url().includes('/title') && response.request().method() === 'PATCH'
    );
    await titleInput.fill(updatedTaskTitle);
    await htmxTriggerChange(titleInput);
    await updateTitlePromise;
    await page.waitForLoadState('networkidle');

    // Verify change reflected in board task list (close modal first)
    await detailDialog.locator('button:has-text("Close")').click();
    await expect(detailDialog).not.toBeVisible();
    await expect(taskCard.locator('h4')).toContainText(updatedTaskTitle);

    // 8. Re-open and Delete the Task
    await taskCard.click();
    await expect(detailDialog).toBeVisible();

    // Trigger delete
    const taskDeleteResponse = page.waitForResponse(
      (response) => response.url().includes('/delete') && response.request().method() === 'POST'
    );
    page.once('dialog', (dialog) => dialog.accept()); // Accept confirm alert dialog
    await detailDialog.locator('button:has-text("Delete Task")').click();
    await taskDeleteResponse;

    // Wait for the client-side redirect and reload to complete
    await page.waitForLoadState('networkidle');

    await expect(detailDialog).not.toBeVisible();

    // Verify task is gone
    await expect(page.locator('.kanban-column').nth(1).locator('.task-card')).not.toBeVisible();

    // 9. Delete Board
    await page.click('text=Edit Board');
    const boardEditDialog = page.locator('dialog[open]');
    await expect(boardEditDialog).toBeVisible();

    const boardDeleteResponse = page.waitForResponse(
      (response) => response.url().includes('/delete') && response.request().method() === 'POST'
    );
    page.once('dialog', (dialog) => dialog.accept());
    await boardEditDialog.locator('button:has-text("Delete Board")').click();
    await boardDeleteResponse;
    await page.waitForLoadState('networkidle');

    // Should redirect back to Team Page
    await expect(page).toHaveURL(/\/teams\/e2e-team-/);
    try {
      await expect(page.locator('.team-meta')).toContainText('0 boards');
    } catch (e) {
      console.log('HTML CONTENT ON FAILURE:', await page.content());
      throw e;
    }

    // 10. Delete Team
    await page.click('text=Edit Team');
    const teamEditDialog = page.locator('dialog[open]');
    await expect(teamEditDialog).toBeVisible();

    const teamDeleteResponse = page.waitForResponse(
      (response) => response.url().includes('/delete') && response.request().method() === 'POST'
    );
    page.once('dialog', (dialog) => dialog.accept());
    await teamEditDialog.locator('button:has-text("Delete Team")').click();
    await teamDeleteResponse;
    await page.waitForLoadState('networkidle');

    // Should redirect back to Dashboard
    await expect(page).toHaveURL('/dashboard');
  });
});
